interface I18nContextType {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: (key: string) => string;
}

const I18nContext = createContext<I18nContextType | undefined>(undefined);

export const useI18n = () => {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error('useI18n must be used within I18nProvider');
  }
  return context;
};

const SUPPORTED_LANGS: Language[] = ['pt', 'en', 'es', 'fr', 'de', 'it', 'ar', 'zh', 'ru', 'hi'];

function detectBrowserLanguage(): Language {
  const browserLang = navigator.language?.split('-')[0]?.toLowerCase() || 'pt';
  if (SUPPORTED_LANGS.includes(browserLang as Language)) {
    return browserLang as Language;
  }
  return 'pt';
}

export const I18nProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<Language>(() => {
    const saved = localStorage.getItem('navanhula_lang');
    if (saved && SUPPORTED_LANGS.includes(saved as Language)) {
      return saved as Language;
    }
    return detectBrowserLanguage();
  });

  const setLanguage = useCallback(async (lang: Language) => {
    setLanguageState(lang);
    localStorage.setItem('navanhula_lang', lang);
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    
    // Persist to user profile if authenticated
    try {
      const { data: { session } } = await supabase.auth.getSession();
      if (session?.user) {
        await supabase
          .from('profiles')
          .update({ language: lang })
          .eq('id', session.user.id);
      }
    } catch (error) {
      console.error('Error persisting language preference:', error);
    }
  }, []);


  useEffect(() => {
    document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';

    const loadProfileLanguage = async () => {
      try {
        const { data: { session } } = await supabase.auth.getSession();
        if (session?.user) {
          const { data: profile } = await supabase
            .from('profiles')
            .select('language')
            .eq('id', session.user.id)
            .single();
          
          if (profile?.language && profile.language !== language && SUPPORTED_LANGS.includes(profile.language as Language)) {
            setLanguageState(profile.language as Language);
            localStorage.setItem('navanhula_lang', profile.language);
          }
        }
      } catch (error) {
        console.warn('Could not load profile language:', error);
      }
    };

    loadProfileLanguage();
  }, []);


  const t = useCallback((key: string): string => {
    return translations[language]?.[key] || translations['pt']?.[key] || translations['en']?.[key] || key;
  }, [language]);

  return (
    <I18nContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </I18nContext.Provider>
  );
};

export const useTranslation = useI18n;
